ALTER FUNCTION  "TNX_LASTGRPO_PRICE"(IN ItemCode VARCHAR(100),IN UomEntry VARCHAR(100),IN DocDate DATE,IN BPLID INTEGER)
RETURNS LastGrpoPrice DOUBLE LANGUAGE SQLSCRIPT  
AS
BEGIN 
SELECT IFNULL(X."Price", 0) INTO LastGrpoPrice FROM DUMMY
LEFT JOIN(SELECT PL."Price"
FROM "OPDN" P
INNER JOIN "PDN1" PL ON PL."DocEntry" = P."DocEntry"
WHERE PL."ItemCode" = :ItemCode
AND PL."UomEntry" = :UomEntry
AND P."DocDate" < :DocDate
AND IFNULL(P."CANCELED", 'N') = 'N'
AND P."BPLId"=:BPLID
ORDER BY P."DocDate" DESC, P."DocEntry" DESC LIMIT 1) X ON 1 = 1;

END;