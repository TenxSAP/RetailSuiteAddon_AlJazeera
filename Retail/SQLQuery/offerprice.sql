CREATE PROCEDURE "offerprice"
(
    IN Itemcode VARCHAR(15),
    IN BranchID INTEGER
)
LANGUAGE SQLSCRIPT
SQL SECURITY INVOKER
AS
BEGIN

    SELECT 
        COALESCE(ROUND(MIN(A1."U_OFPRWVAT"), 2), 0) AS "PromotionPrice"
    FROM "@TNX_ITEMDISC" A0
    INNER JOIN "@TNX_ITEMDISC_C0" A1 
        ON A0."DocEntry" = A1."DocEntry"
    WHERE UPPER(A0."U_STATUS") = 'ACTIVE'
      AND TO_CHAR(CURRENT_TIMESTAMP, 'YYYYMMDDHH24MI') >= 
            TO_CHAR(A1."U_FRMDATE", 'YYYYMMDD') || LPAD(IFNULL(A0."U_FRMTIME", 0), 4, '0')
             AND TO_CHAR(CURRENT_TIMESTAMP, 'YYYYMMDDHH24MI') <= TO_CHAR(ADD_DAYS(A1."U_TODATE", 1), 'YYYYMMDD') || LPAD(IFNULL(A0."U_TOTIME",0),4,'0')         
      AND A0."U_BPLID" = :BranchID
      AND A1."U_ITMCODE" = :Itemcode;

END;